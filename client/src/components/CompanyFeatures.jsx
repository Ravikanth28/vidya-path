    useEffect(load, []);

    const create = async () => {
        if (!form.company_name.trim() || !form.title.trim()) return setError('Company name and title required');
        setCreating(true); setError('');
        try { await axios.post(`${API}/api/company/interviews/create`, form); setShowCreate(false); setForm({ company_name: '', title: '', description: '', duration_minutes: 60, difficulty: 'medium', skills_covered: [], max_attempts: 0 }); load(); }
        catch (e) { setError(e.response?.data?.error || e.message); }
        finally { setCreating(false); }
    };

    const toggle = async (id) => { try { await axios.put(`${API}/api/company/interviews/${id}/toggle`); load(); } catch (e) { setError(e.message); } };
    const del = async (id) => { if (!confirm('Delete this test and all attempts?')) return; try { await axios.delete(`${API}/api/company/interviews/${id}`); load(); } catch (e) { setError(e.message); } };
    const loadAttempts = async (id) => {
        if (viewAttempts === id) { setViewAttempts(null); return; }
        try { const { data } = await axios.get(`${API}/api/company/interviews/${id}/attempts`); setAttempts(data); setViewAttempts(id); }
        catch (e) { setAttempts([]); setViewAttempts(id); }
    };

    const saveLimit = async (id) => {
        try { await axios.put(`${API}/api/company/interviews/${id}/update-limits`, { max_attempts: parseInt(limitValue) || 0 }); setEditingLimit(null); load(); }
        catch (e) { setError(e.message); }
    };

